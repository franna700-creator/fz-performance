import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const htmlPath=path.join(root,'dist','index.html');
const outDir=path.join(root,'dist','assets');
const jsSrc=path.join(root,'src','today-redesign-v2.js');
const cssSrc=path.join(root,'src','today-redesign-v2.css');
const photoCssSrc=path.join(root,'src','fz-training-hero-data.css');
for(const input of [htmlPath,jsSrc,cssSrc,photoCssSrc])if(!fs.existsSync(input))throw new Error(`TODAY v2 build input missing: ${input}`);
let html=fs.readFileSync(htmlPath,'utf8');
if(!html.includes('/assets/today-redesign-v2.css'))html=html.replace('</head>','<link href="/assets/today-redesign-v2.css" rel="stylesheet"/><link href="/assets/fz-training-hero-data.css" rel="stylesheet"/></head>');
else if(!html.includes('/assets/fz-training-hero-data.css'))html=html.replace('/assets/today-redesign-v2.css" rel="stylesheet"/>','/assets/today-redesign-v2.css" rel="stylesheet"/><link href="/assets/fz-training-hero-data.css" rel="stylesheet"/>');
if(!html.includes('/assets/today-redesign-v2.js'))html=html.replace('</body>','<script src="/assets/today-redesign-v2.js" type="module"></script></body>');
fs.writeFileSync(htmlPath,html);
fs.copyFileSync(jsSrc,path.join(outDir,'today-redesign-v2.js'));
fs.copyFileSync(cssSrc,path.join(outDir,'today-redesign-v2.css'));
fs.copyFileSync(photoCssSrc,path.join(outDir,'fz-training-hero-data.css'));
console.log('PASS TODAY redesign v2 assets wired');
