import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { buildEventDemandTaxonomyProfile, compareTaxonomyProfiles, validateEventDemandTaxonomy } from '../lib/event-demand-taxonomy.js';
const taxonomy=JSON.parse(await fs.readFile('config/event-demand-taxonomy.json','utf8'));
const formats=JSON.parse(await fs.readFile('config/event-format-profiles.json','utf8'));
assert.equal(validateEventDemandTaxonomy(taxonomy).ok,true);
const byId=id=>formats.profiles.find(x=>x.id===id);
const deadly=buildEventDemandTaxonomyProfile(byId('deadly-dozen-track-male-sa'));
const hyrox=buildEventDemandTaxonomyProfile(byId('hyrox-open-men-2025-26'));
const half=buildEventDemandTaxonomyProfile(byId('half-marathon-road'));
assert.equal(deadly.structure['running.bout_count'],12);
assert.equal(deadly.structure['running.typical_bout_m'],400);
assert.equal(hyrox.structure['running.bout_count'],8);
assert.equal(hyrox.structure['running.typical_bout_m'],1000);
assert.equal(half.structure['running.mode'],'CONTINUOUS');
assert.ok(deadly.scores['running.compromised']>0.85);
assert.ok(hyrox.scores['modality.sled']>0);
assert.equal(half.scores['modality.sled'],0);
assert.equal(half.scores['pacing.interrupted'],0);
const d2h=compareTaxonomyProfiles(deadly,hyrox);
assert.equal(d2h.interchangeable,false);
assert.equal(d2h.diagnosticOnly,true);
assert.equal(d2h.authoritativeTransferScore,false);
assert.ok(d2h.shared.some(x=>x.dimensionId==='running.compromised'));
assert.ok(d2h.gaps.some(x=>x.dimensionId==='modality.sled'));
const h2h=compareTaxonomyProfiles(half,hyrox);
assert.ok(h2h.shared.some(x=>x.dimensionId==='running.economy'));
assert.ok(h2h.gaps.some(x=>x.dimensionId==='sequencing.mixed_modality_repeatability'));
console.log('PASS event demand taxonomy v1: common language distinguishes shared transfer from event equivalence');
