import assert from 'node:assert/strict';
import fs from 'node:fs';
const schema = JSON.parse(fs.readFileSync('schemas/event-intake.schema.json','utf8'));
assert.equal(schema.$schema,'https://json-schema.org/draft/2020-12/schema');
assert.ok(schema.required.includes('knowledgeStatus'));
assert.ok(schema.properties.knowledgeStatus.enum.includes('RESEARCH_REQUIRED'));
assert.ok(schema.properties.knowledgeStatus.enum.includes('QUALIFIED'));
assert.ok(schema.properties.status.enum.includes('CANDIDATE'),'considering events must remain representable before scheduling');
assert.ok(schema.properties.participationStatus.enum.includes('CONSIDERING'));
assert.ok(schema.properties.participationStatus.enum.includes('CONFIRMED'));
assert.ok(schema.properties.dateWindow,'approximate event dates must be representable without inventing an exact date');
assert.ok(schema.allOf?.[0]?.then?.anyOf?.some(rule=>rule.required?.includes('dateWindow')),'non-candidate event intake must accept a date range');
console.log('PASS event intake schema knowledge + variable participation/date contract');
